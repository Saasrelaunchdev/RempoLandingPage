// The captions, from the narration's timing: one cue per phrase, split at sentence ends and commas so a cue stays
// short enough for the page to draw in one or two lines (the testimonial's captions are cut the same way).
const MAX = 58;

const stamp = (s) => {
  const ms = Math.round(s * 1000);
  const h = Math.floor(ms / 3600000), m = Math.floor(ms / 60000) % 60, sec = Math.floor(ms / 1000) % 60;
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(sec).padStart(2, '0')}.${String(ms % 1000).padStart(3, '0')}`;
};

function wordsOf(line) {
  if (line.words) return line.words;
  // no word timing: spread the words over the line by their length
  const ws = line.text.split(' '), total = line.text.length;
  let at = 0;
  return ws.map((w) => { const t = line.start + ((line.end - line.start) * at) / total; at += w.length + 1; return { w, t }; });
}

export function phrases(line) {
  const ws = wordsOf(line), out = [];
  let cur = [];
  const len = (a) => a.map((x) => x.w).join(' ').length;
  ws.forEach((x, i) => {
    cur.push(x);
    const next = ws[i + 1];
    const endsClause = /[.,!?]$/.test(x.w);
    const tooLong = next && len([...cur, next]) > MAX;
    if (!next || (endsClause && len(cur) >= 16 && (/[.!?]$/.test(x.w) || len(cur) >= 26)) || tooLong) {
      out.push(cur);
      cur = [];
    }
  });
  return out.map((p, i) => ({
    text: p.map((x) => x.w).join(' '),
    start: i === 0 ? line.start : p[0].t,
    end: i < out.length - 1 ? out[i + 1][0].t : line.end,
  }));
}

export function captions(timings) {
  const cues = [];
  timings.lines.forEach((line, li) => {
    const nextStart = timings.lines[li + 1] ? timings.lines[li + 1].start : timings.duration;
    phrases(line).forEach((p, i, all) => {
      const end = i === all.length - 1 ? Math.min(p.end + 0.45, nextStart - 0.05) : p.end;
      cues.push({ a: Math.max(0, i === 0 ? p.start - 0.05 : p.start), b: end, text: p.text });
    });
  });
  return 'WEBVTT\n\nNOTE The narration of the hero video, "Your reputation, as good as your work". Generated by hero-video/tools/captions.mjs from the voiceover timing.\n\n' +
    cues.map((c, i) => `${i + 1}\n${stamp(c.a)} --> ${stamp(c.b)}\n${c.text}\n`).join('\n');
}
